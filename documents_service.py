ONES = ["", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine",
        "Ten", "Eleven", "Twelve", "Thirteen", "Fourteen", "Fifteen", "Sixteen",
        "Seventeen", "Eighteen", "Nineteen"]
TENS = ["", "", "Twenty", "Thirty", "Forty", "Fifty", "Sixty", "Seventy", "Eighty", "Ninety"]


def _words_under_1000(n):
    out = []
    if n >= 100:
        out.append(ONES[n // 100] + " Hundred")
        n %= 100
    if 0 < n < 20:
        out.append(ONES[n])
    elif n >= 20:
        out.append(TENS[n // 10])
        if n % 10:
            out.append(ONES[n % 10])
    return " ".join(out)


def amount_to_words(cents: int) -> str:
    """Convert an amount in cents to the words used on the check amount line."""
    dollars, remainder = divmod(int(cents or 0), 100)
    if dollars == 0:
        parts = "Zero"
    elif dollars < 1_000_000:
        parts = _words_under_1000(dollars)
    else:
        millions, rest = divmod(dollars, 1_000_000)
        parts = _words_under_1000(millions) + " Million"
        if rest:
            parts += " " + _words_under_1000(rest)
    return f"{parts.title()} and {remainder:02d}/100 Dollars"


def _money(cents: int) -> str:
    try:
        return f"${int(cents or 0) / 100:,.2f}"
    except (TypeError, ValueError):
        return "$0.00"


def _pdf_text(value) -> str:
    """Sanitize a value for core-font (latin-1) PDF cells.

    Core PDF fonts can only encode latin-1; em-dashes, smart quotes, bullets,
    etc. otherwise raise FPDFUnicodeEncodingException and kill the whole PDF.
    We approximate the common ones and drop anything else.
    """
    text = str(value or "")
    return (
        text.replace("\u2014", "--")   # em dash
        .replace("\u2013", "-")        # en dash
        .replace("\u2018", "'").replace("\u2019", "'")   # curly single quotes
        .replace("\u201c", '"').replace("\u201d", '"')   # curly double quotes
        .replace("\u2026", "...")      # ellipsis
        .replace("\u00b7", ".")
        .replace("\u2022", "-")        # bullet
        .encode("latin-1", "replace").decode("latin-1")
    )


