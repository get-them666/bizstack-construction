def render_pay_stub_pdf(stub) -> bytes:
    pdf = _BasePdf(format="Letter")
    pdf.add_page()
    pdf.set_margins(20, 15, 20)

    pdf.set_font("helvetica", "B", 17)
    pdf.set_text_color(15, 20, 30)
    pdf.cell(0, 8, "Broom Service", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("helvetica", "", 9)
    pdf.set_text_color(110, 110, 120)
    pdf.cell(0, 5, "PAY STUB", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(3)

    y = pdf.get_y()
    pdf.set_draw_color(79, 70, 229)
    pdf.set_line_width(0.7)
    pdf.line(20, y, pdf.w - 20, y)
    pdf.ln(4)

    info = [
        ("Employee", stub.get("worker_name", "")),
        ("Pay period", f"{stub.get('period_start')}  to  {stub.get('period_end')}"),
        ("Jobs completed", str(stub.get("job_count", 0))),
        ("Check number", str(stub.get("check_number") or "--")),
        ("Pay date", str(stub.get("pay_date") or "________________")),
    ]
    pdf.set_font("helvetica", "", 10)
    for label, val in info:
        pdf.set_text_color(90, 90, 100)
        pdf.cell(50, 6, label.upper(), new_x="END")
        pdf.set_text_color(20, 20, 25)
        pdf.cell(0, 6, _pdf_text(val), new_x="LMARGIN", new_y="NEXT")
    pdf.ln(4)

    rows = [
        ("GROSS PAY", stub.get("gross_cents", 0), False),
        ("Federal withholding", stub.get("fed_cents", 0), True),
        ("State withholding", stub.get("state_cents", 0), True),
        ("FICA / Medicare", stub.get("fica_cents", 0), True),
        ("Other deductions", stub.get("other_cents", 0), True),
    ]
    pdf.set_font("helvetica", "", 10.5)
    for label, cents, deduct in rows:
        pdf.set_draw_color(230, 230, 235)
        pdf.set_line_width(0.3)
        pdf.line(20, pdf.get_y() + 6, pdf.w - 20, pdf.get_y() + 6)
        if deduct:
            pdf.set_text_color(180, 40, 40)
        else:
            pdf.set_text_color(20, 20, 25)
        pdf.cell(0, 7, label, new_x="END")
        pdf.cell(0, 7, _money(cents), align="R", new_x="LMARGIN", new_y="NEXT")

    pdf.ln(2)
    pdf.set_fill_color(16, 185, 129)
    pdf.set_font("helvetica", "B", 12)
    pdf.set_text_color(255, 255, 255)
    pdf.set_draw_color(16, 185, 129)
    pdf.rect(20, pdf.get_y(), pdf.w - 40, 9, style="F")
    pdf.set_xy(20, pdf.get_y() + 1)
    pdf.cell(pdf.w - 40, 7, "NET PAY", align="C")

    net = (stub.get("gross_cents") or 0) - (stub.get("fed_cents") or 0) - (stub.get("state_cents") or 0) - (stub.get("fica_cents") or 0) - (stub.get("other_cents") or 0)
    pdf.set_font("helvetica", "", 11)
    pdf.set_text_color(20, 20, 25)
    pdf.set_fill_color(16, 185, 129)
    pdf.set_text_color(255, 255, 255)
    pdf.set_xy(20, pdf.get_y() + 2)
    pdf.cell(pdf.w - 40, 7, _money(net), align="C")
    pdf.set_text_color(20, 20, 25)

    pdf.ln(14)
    pdf.set_font("helvetica", "I", 8)
    pdf.set_text_color(150, 150, 155)
    pdf.multi_cell(0, 4.5, _pdf_text("Note: This is a generated record from the Broom Service accounting module. Verify withholdings with your accountant."))

    # QR-ish reference
    pdf.set_font("helvetica", "", 8)
    pdf.set_text_color(90, 90, 100)
    pdf.set_xy(20, pdf.h - 24)
    pdf.cell(0, 5, _pdf_text(f"Stub ID: {stub.get('id', '')}  ·  Generated {stub.get('generated_at', '')}"))

    return bytes(pdf.output())


def render_check_pdf(check: dict) -> bytes:
    """Printable check + attached stub on one letter page.

    pays like: check['payee'], check['amount_cents'], check['check_number'],
    check['date'], check['memo'], check['stub'] (dict for stub rows), and
    check['bank']['name'/'holder'/'routing'/'account'/'address']."""

    pdf = _BasePdf(format="Letter")
    pdf.add_page()
    pdf.set_margins(20, 15, 20)

    bank = check.get("bank", {}) or {}

    # --- Stub (top third) ---
    pdf.set_font("helvetica", "B", 12)
    pdf.set_text_color(20, 20, 25)
    pdf.cell(0, 6, _pdf_text(f"CHECK STUB  ·  {check.get('check_number', '')}"), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("helvetica", "", 9)
    pdf.set_text_color(90, 90, 100)
    pdf.cell(0, 5, _pdf_text(bank.get('holder', 'Broom Service')), new_x="LMARGIN", new_y="NEXT")
    pdf.cell(0, 5, _pdf_text("Pay to:  " + str(check.get("payee", ""))), new_x="LMARGIN", new_y="NEXT")
    pdf.cell(0, 5, _pdf_text("Date:  " + str(check.get("date", ""))), new_x="LMARGIN", new_y="NEXT")
    pdf.ln(2)

    stub_rows = check.get("stub") or [("Amount", check.get("amount_cents", 0))]
    pdf.set_font("helvetica", "", 9)
    for label, cents in stub_rows:
        pdf.cell(0, 5.5, _pdf_text(label), new_x="END")
        pdf.cell(0, 5.5, _money(cents), align="R", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(2)
    pdf.set_font("helvetica", "B", 10)
    pdf.cell(0, 6, "TOTAL", new_x="END")
    pdf.cell(0, 6, _money(check.get("amount_cents", 0)), align="R", new_x="LMARGIN", new_y="NEXT")

    # perforation line
    pdf.set_draw_color(180, 180, 190)
    pdf.set_line_width(0.4)
    y = pdf.get_y() + 6
    pdf.set_dash_pattern(dash=2, gap=2)
    pdf.line(20, y, pdf.w - 20, y)
    pdf.set_dash_pattern()
    pdf.ln(10)

    # --- Check body ---
    pdf.set_font("helvetica", "B", 14)
    pdf.set_text_color(20, 20, 25)
    pdf.cell(0, 8, _pdf_text(bank.get("holder", "Broom Service")), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("helvetica", "", 8)
    pdf.set_text_color(90, 90, 100)
    pdf.multi_cell(0, 4, _pdf_text(str(bank.get("address", "")) + (" " + str(bank.get("city_state_zip", ""))).strip()))

    pdf.set_font("helvetica", "", 9)
    pdf.set_text_color(20, 20, 25)
    date_str = str(check.get("date", ""))
    pdf.cell(70, 7, "")  # left spacer
    pdf.cell(0, 7, _pdf_text("DATE  " + date_str), new_x="LMARGIN", new_y="NEXT")
    pdf.ln(2)

    # pay to / amount box row
    pdf.cell(8, 8, "")
    pdf.set_font("helvetica", "", 8)
    pdf.set_text_color(90, 90, 100)
    pdf.cell(30, 5, "PAY TO THE ORDER OF")
    pdf.set_font("helvetica", "B", 11)
    pdf.set_text_color(20, 20, 25)
    pdf.cell(0, 8, _pdf_text("  " + str(check.get("payee", "")) + "  "), border=1, new_x="END")
    # amount box
    pdf.cell(0, 8, "")
    pdf.set_draw_color(90, 90, 100)
    pdf.set_line_width(0.4)
    pdf.set_xy(pdf.l_margin, pdf.get_y())
    box_x = pdf.w - pdf.r_margin - 45
    pdf.set_font("helvetica", "B", 11)
    y0 = pdf.get_y()
    pdf.rect(box_x, y0, 45, 8)
    pdf.set_xy(box_x, y0 + 1.5)
    pdf.cell(45, 5, _money(check.get("amount_cents", 0)), align="C")
    pdf.set_xy(pdf.l_margin, y0)
    pdf.ln(9)

    # amount in words
    pdf.cell(8, 7, "")
    pdf.set_font("helvetica", "", 8)
    pdf.set_text_color(90, 90, 100)
    pdf.cell(30, 5, "AMOUNT")
    pdf.set_font("helvetica", "", 9.5)
    pdf.set_text_color(20, 20, 25)
    pdf.cell(pdf.w - pdf.l_margin - pdf.r_margin - 40, 7, _pdf_text("  " + amount_to_words(check.get("amount_cents", 0)) + "  "), border=1, new_x="LMARGIN", new_y="NEXT")

    memo = check.get("memo") or ""
    pdf.ln(2)
    pdf.cell(8, 7, "")
    pdf.set_font("helvetica", "", 8)
    pdf.set_text_color(90, 90, 100)
    pdf.cell(20, 5, "MEMO")
    pdf.set_font("helvetica", "", 9.5)
    pdf.set_text_color(20, 20, 25)
    pdf.cell(0, 7, _pdf_text("  " + memo), new_x="LMARGIN", new_y="NEXT")
    pdf.ln(5)

    # signature
    pdf.cell(8, 6, "")
    pdf.set_draw_color(60, 60, 70)
    pdf.set_line_width(0.5)
    pdf.line(pdf.l_margin + 30, pdf.get_y(), pdf.l_margin + 120, pdf.get_y())
    pdf.ln(6)
    pdf.cell(8, 5, "")
    pdf.set_font("helvetica", "", 8)
    pdf.set_text_color(90, 90, 100)
    pdf.cell(120, 5, "Authorized Signature")
    pdf.ln(8)

    # MICR style line (visual — print on pre-encoded stock for real checks)
    pdf.set_font("Courier", "B", 9)
    pdf.set_text_color(10, 10, 15)
    micr = f"|:000000000:{bank.get('routing', '').zfill(9)}:{bank.get('account', '').zfill(12)}:{str(check.get('check_number', '')).zfill(4)}||"
    pdf.set_xy(pdf.l_margin, pdf.h - 24)
    pdf.cell(0, 5, micr)

    return bytes(pdf.output())


