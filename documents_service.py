def _field_value(values: dict, key: str) -> str:
    val = (values or {}).get(key)
    return "" if val is None else str(val).strip()


class _BasePdf(FPDF):
    def footer(self):
        self.set_y(-12)
        self.set_font("helvetica", size=8)
        self.set_text_color(140, 140, 150)
        self.cell(0, 8, _pdf_text(f"Page {self.page_no()} - Generated by Broom Service"), align="C")


def render_doc_pdf(form: dict, values: dict) -> bytes:
    pdf = _BasePdf(format="Letter")
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.add_page()
    pdf.set_margins(20, 15, 20)

    pdf.set_font("helvetica", "B", 16)
    pdf.set_text_color(20, 20, 25)
    pdf.multi_cell(0, 7, _pdf_text(form.get("title", "Document")), align="L")

    pdf.set_font("helvetica", "", 9)
    pdf.set_text_color(110, 110, 120)
    pdf.set_x(pdf.l_margin)
    pdf.multi_cell(0, 5, _pdf_text(f"DATE: {_field_value(values, 'date') or '________________'}"))

    y = pdf.get_y()
    pdf.set_draw_color(79, 70, 229)
    pdf.set_line_width(0.6)
    pdf.line(20, y, pdf.w - 20, y)
    pdf.ln(4)

    for section in form.get("sections", []):
        pdf.set_font("helvetica", "B", 12)
        pdf.set_text_color(79, 70, 229)
        pdf.ln(2)
        pdf.multi_cell(0, 6, _pdf_text(section.get("heading", "")))
        pdf.ln(1)
        for fld in section.get("fields", []):
            label = fld.get("label", fld.get("key", ""))
            val = _field_value(values, fld.get("key"))
            line = f"{label}:  {val}" if val else f"{label}:"
            pdf.set_font("helvetica", "", 10)
            pdf.set_text_color(20, 20, 25)
            pdf.multi_cell(0, 5, _pdf_text(line))
            if not val:
                pdf.set_draw_color(200, 200, 210)
                pdf.set_line_width(0.3)
                pdf.line(20, pdf.get_y() + 1, min(pdf.w - 40, 20 + 150), pdf.get_y() + 1)
                pdf.ln(3)
            else:
                pdf.ln(2)

    for clause in form.get("agreements", []):
        pdf.ln(2)
        pdf.set_draw_color(200, 200, 210)
        pdf.set_line_width(0.3)
        pdf.line(20, pdf.get_y(), pdf.w - 20, pdf.get_y())
        pdf.ln(3)
        pdf.set_font("helvetica", "", 10)
        pdf.set_text_color(30, 30, 40)
        pdf.multi_cell(0, 5.2, _pdf_text("•  " + clause))

    if form.get("signatories"):
        pdf.ln(6)
        halfway = (pdf.w - 40) / 2
        for sig in form["signatories"]:
            pdf.ln(6)
            pdf.set_draw_color(60, 60, 70)
            pdf.set_line_width(0.4)
            pdf.line(20, pdf.get_y(), 20 + (halfway - 10), pdf.get_y())
            pdf.set_font("helvetica", "", 9)
            pdf.set_text_color(90, 90, 100)
            pdf.set_xy(20, pdf.get_y() + 2)
            pdf.cell(0, 5, _pdf_text(sig + " Signature & Date"))
            pdf.ln(10)

    if form.get("disclaimer"):
        pdf.ln(2)
        pdf.set_font("helvetica", "I", 8)
        pdf.set_text_color(150, 150, 155)
        pdf.multi_cell(0, 4.5, _pdf_text("Note: " + form["disclaimer"]))

    return bytes(pdf.output())


def render_doc_docx(form: dict, values: dict) -> bytes:
    from docx import Document
    from docx.shared import Pt, RGBColor

    doc = Document()
    styles = doc.styles["Normal"]
    styles.font.name = "Calibri"
    styles.font.size = Pt(10.5)

    h = doc.add_heading(form.get("title", "Document"), level=0)
    h.runs[0].font.color.rgb = RGBColor(0x10, 0x14, 0x19)

    date_line = doc.add_paragraph()
    r = date_line.add_run(f"DATE: {_field_value(values, 'date') or '________________'}")
    r.font.size = Pt(9)
    r.font.color.rgb = RGBColor(0x6E, 0x6E, 0x78)

    def field_line(field):
        label = field.get("label", field.get("key", ""))
        val = _field_value(values, field.get("key"))
        if val:
            p = doc.add_paragraph(f"{label}:  {val}")
        else:
            p = doc.add_paragraph(f"{label}:  " + "_" * 42)
        p.paragraph_format.space_after = Pt(4)
        return p

    for section in form.get("sections", []):
        doc.add_heading(section.get("heading", ""), level=1)
        for fld in section.get("fields", []):
            field_line(fld)

    for clause in form.get("agreements", []):
        p = doc.add_paragraph(style="List Bullet")
        p.add_run(clause)

    if form.get("signatories"):
        doc.add_paragraph()
        for sig in form["signatories"]:
            doc.add_paragraph()
            sp = doc.add_paragraph(f"____________________________________   {sig} Signature & Date")
            sp.paragraph_format.space_after = Pt(10)

    if form.get("disclaimer"):
        dp = doc.add_paragraph()
        dr = dp.add_run("Note: " + form["disclaimer"])
        dr.font.size = Pt(8)
        dr.font.italic = True
        dr.font.color.rgb = RGBColor(0x96, 0x96, 0x9B)

    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def render_document(form: dict, values: dict, fmt: str) -> bytes:
    if fmt == "docx":
        return render_doc_docx(form, values)
    return render_doc_pdf(form, values)


