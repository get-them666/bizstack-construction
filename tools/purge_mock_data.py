#!/usr/bin/env python3
"""Remove the fabricated/demo rows from the Construction database.

WHY THIS IS A SCRIPT AND NOT A MIGRATION
----------------------------------------
Every row this touches is either demonstrably generated by the app (the demo
permit fallback, the "Month 1 - Whole Home Renovation" bid board) or a social
radar name with no address, phone, email or communication history. None of it
is customer data. Still, deleting production rows is irreversible, so this
does three things every time:

  1. Writes every row it will delete to CSV first (default ``~/bizstack-construction-backups/``).
  2. Defaults to a DRY RUN. ``--commit`` is required to delete anything.
  3. Prints the exact counts and the selection rules before touching a row.

Run it against a Railway tunnel, never ``postgres.railway.internal`` directly:

    railway connect Postgres --tunnel-only      # prints the local port
    export DATABASE_URL='postgresql://postgres:PASSWORD@127.0.0.1:PORT/construction'
    ./venv/bin/python tools/purge_mock_data.py
    ./venv/bin/python tools/purge_mock_data.py --commit

What is selected
----------------
* job_leads.is_demo = true                    (the old demo-permit fallback)
* bid_opportunities from source
  'historical_owner_supplied' named "Month N - ..." (the fabricated finished
  jobs that populated the "won" column)
* projects created for those fake bids
* leads from linkedin/reddit that have no phone, no real email, no comms,
  no payments and no projects -- names scraped from a post, not customers
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

import psycopg
from psycopg.rows import dict_row

# Running `python tools/purge_mock_data.py` puts tools/ on sys.path, not the
# repo root, so `bizstack_leads` is not importable. Add the repo root explicitly.
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

FAKE_BID_SQL = """
    SELECT * FROM bid_opportunities
    WHERE source = 'historical_owner_supplied'
      AND name ~ '^Month [0-9]+ - '
"""

SOCIAL_SQL = """
    SELECT l.* FROM leads l
    WHERE l.company = 'construction'
      AND LOWER(l.source) IN ('linkedin', 'reddit')
      AND COALESCE(TRIM(l.phone), '') = ''
      AND (COALESCE(TRIM(l.email), '') = '' OR LOWER(l.email) LIKE '%%@lead.local')
      AND NOT EXISTS (SELECT 1 FROM comms_logs c WHERE c.lead_id = l.id)
      AND NOT EXISTS (SELECT 1 FROM payments p WHERE p.lead_id = l.id)
      AND NOT EXISTS (SELECT 1 FROM projects pr WHERE pr.lead_id = l.id)
"""

DEMO_PERMIT_SQL = "SELECT * FROM job_leads WHERE is_demo = true"


def _backup(outdir: Path, name: str, rows: list[dict]) -> Path | None:
    if not rows:
        return None
    path = outdir / f"{name}.csv"
    # Union of keys, because a query may return rows with different shapes.
    fields = sorted({k for row in rows for k in row.keys()})
    with path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=fields)
        writer.writeheader()
        for row in rows:
            writer.writerow({k: _cell(row.get(k)) for k in fields})
    return path


def _cell(value):
    if value is None:
        return ""
    if isinstance(value, (dict, list)):
        return json.dumps(value, default=str)
    return str(value)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--database-url", default=os.getenv("DATABASE_URL", ""),
                        help="Defaults to $DATABASE_URL")
    parser.add_argument("--commit", action="store_true",
                        help="Actually delete. Without this the run is read-only.")
    parser.add_argument("--backup-dir", default=os.path.expanduser(
        "~/bizstack-construction-backups"))
    args = parser.parse_args()

    if not args.database_url:
        print("DATABASE_URL is not set. Pass --database-url or export it.", file=sys.stderr)
        return 2
    if "railway.internal" in args.database_url:
        print("Refusing to run against *.railway.internal from this machine. "
              "Open a tunnel and use 127.0.0.1.", file=sys.stderr)
        return 2

    stamp = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S")
    outdir = Path(args.backup_dir).expanduser() / f"purge-{stamp}"
    outdir.mkdir(parents=True, exist_ok=True)

    with psycopg.connect(args.database_url, row_factory=dict_row) as conn:
        with conn.cursor() as cur:
            cur.execute(DEMO_PERMIT_SQL)
            demo_permits = cur.fetchall()

            cur.execute(FAKE_BID_SQL)
            fake_bids = cur.fetchall()
            fake_bid_ids = [r["id"] for r in fake_bids]

            fake_projects = []
            if fake_bid_ids:
                cur.execute(
                    "SELECT * FROM projects WHERE bid_id = ANY(%s) "
                    "OR (name ~ '^Month [0-9]+ - ' AND created_at::date = DATE '2026-10-23');",
                    (fake_bid_ids,),
                )
                fake_projects = cur.fetchall()

            cur.execute(SOCIAL_SQL)
            social = cur.fetchall()

        print("Selected for removal")
        print(f"  demo job_leads                 {len(demo_permits)}")
        print(f"  fabricated bids                {len(fake_bids)}")
        print(f"  projects from those bids       {len(fake_projects)}")
        print(f"  unreachable social-radar leads  {len(social)}")
        print(f"Backups: {outdir}")

        backups = {
            "demo_job_leads": _backup(outdir, "demo_job_leads", demo_permits),
            "fabricated_bids": _backup(outdir, "fabricated_bids", fake_bids),
            "fake_projects": _backup(outdir, "fake_projects", fake_projects),
            "social_leads": _backup(outdir, "social_leads", social),
        }
        for label, path in backups.items():
            if path:
                print(f"  backed up {label}: {path.name}")

        if not args.commit:
            print("\nDRY RUN. Nothing deleted. Re-run with --commit.")
            print("Samples:")
            for row in fake_bids[:3]:
                print(f"  bid #{row['id']} {row['name']} ${row.get('contract_value')}")
            for row in social[:3]:
                print(f"  lead #{row['id']} {row['name']} ({row['source']})")
            return 0

        deleted = {"projects": 0, "bids": 0, "job_leads": 0, "leads": 0}
        with conn.cursor() as cur:
            if fake_projects:
                ids = [r["id"] for r in fake_projects]
                cur.execute("DELETE FROM projects WHERE id = ANY(%s);", (ids,))
                deleted["projects"] = cur.rowcount
            if fake_bid_ids:
                # bid_costs / documents may reference a bid. They are keyed to
                # these fabricated rows only, so cascade explicitly.
                for table in ("bid_costs", "bid_documents", "bid_invoices", "takeoff_sheets"):
                    cur.execute(
                        f"DELETE FROM {table} WHERE bid_id = ANY(%s);", (fake_bid_ids,))
                cur.execute("DELETE FROM bid_opportunities WHERE id = ANY(%s);",
                            (fake_bid_ids,))
                deleted["bids"] = cur.rowcount
            if demo_permits:
                ids = [r["id"] for r in demo_permits]
                cur.execute("DELETE FROM job_leads WHERE id = ANY(%s);", (ids,))
                deleted["job_leads"] = cur.rowcount
            if social:
                ids = [r["id"] for r in social]
                cur.execute("DELETE FROM leads WHERE id = ANY(%s);", (ids,))
                deleted["leads"] = cur.rowcount
        conn.commit()
        print("\nDeleted")
        for key, count in deleted.items():
            print(f"  {key:12s} {count}")

        # The permit's declared job value is real money attached to a real
        # address. Existing permit leads were created before it was carried
        # onto the lead, so the pipeline showed $0 for the whole supply.
        with conn.cursor() as cur:
            cur.execute("""
                UPDATE leads l
                SET estimate_low_cents = ROUND(j.val * 100)::bigint,
                    estimate_high_cents = ROUND(j.val * 100)::bigint
                FROM (
                    SELECT upper(btrim(address)) AS addr, max(estimated_value) AS val
                    FROM job_leads
                    WHERE COALESCE(estimated_value, 0) > 0
                    GROUP BY 1
                ) j
                WHERE l.company = 'construction'
                  AND l.source = 'permit_finder'
                  AND upper(btrim(l.address)) = j.addr
                  AND l.estimate_low_cents IS NULL;
            """)
            estimates = cur.rowcount
        conn.commit()
        print(f"  permit estimates backfilled {estimates}")

        # Queue columns are cached. Recompute EVERY construction lead, not just
        # the ones with a NULL action: a lead that already had a phone but was
        # stuck in `enrich` will not be fixed by the null-only backfill.
        try:
            from bizstack_leads import store as lead_store
            with conn.cursor() as cur:
                cur.execute("SELECT id FROM leads WHERE company = 'construction' ORDER BY id;")
                ids = [r["id"] for r in cur.fetchall()]
            for lead_id in ids:
                lead_store.recompute(conn, lead_id)
            print(f"Recomputed queue state for {len(ids)} lead(s).")
        except Exception as exc:
            print(f"WARNING: queue recompute failed: {exc}", file=sys.stderr)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
